import Foundation

/// App UI language. Protocol strings, device names, and media metadata retain their original values.
enum MacPlayLocalization {
    static var language = "system"

    static var effectiveLanguage: String {
        let requested = language == "system" ? (Locale.preferredLanguages.first ?? "en") : language
        let code = requested.lowercased()
        if code.hasPrefix("zh") {
            return code.contains("hant") || code.contains("tw") || code.contains("hk") || code.contains("mo") ? "zh-Hant" : "zh-Hans"
        }
        return "en"
    }

    static func translate(_ text: String) -> String {
        let code = effectiveLanguage
        guard code != "zh-Hans", !text.isEmpty else { return text }
        let target = code == "zh-Hant" ? 0 : 1
        if let translation = translations[text] { return target == 0 ? translation.0 : translation.1 }
        // Status details can include a translated app hint followed by the original system explanation.
        if text.contains("\n") { return text.components(separatedBy: "\n").map(translate).joined(separator: "\n") }
        if text.hasPrefix("将在"),text.hasSuffix("秒后重试连接。") {
            let seconds=text.dropFirst(2).dropLast(7)
            return code == "zh-Hant" ? "將在\(seconds)秒後重試連線。" : "Retrying in \(seconds) seconds."
        }
        for (expression, traditional, english) in patterns {
            let range = NSRange(text.startIndex..<text.endIndex, in: text)
            if expression.firstMatch(in: text, range: range) != nil {
                let result = expression.stringByReplacingMatches(in: text, range: range, withTemplate: target == 0 ? traditional : english)
                return result.replacingOccurrences(of: "内建显示器", with: code == "zh-Hant" ? "內建顯示器" : "Built-in Display")
                    .replacingOccurrences(of: "外接显示器", with: code == "zh-Hant" ? "外接顯示器" : "External Display")
            }
        }
        return text
    }

